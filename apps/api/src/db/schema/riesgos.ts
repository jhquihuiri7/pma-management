import { sql } from "drizzle-orm";
import { pgTable, uuid, text, timestamp, integer, boolean, jsonb, index, uniqueIndex } from "drizzle-orm/pg-core";
import {
  riesgosDisponibilidadEnum,
  riesgosEstadoEnum,
  riesgosInstitucionTipoEnum,
  riesgosIslaEnum,
  riesgosRecursoTipoEnum,
} from "./enums.js";
import { users } from "./shared.js";

// Gestión de Riesgos (migration 0035). The CHECK constraints on quantities and
// delegates live in the migration; the API validates the same rules first so
// the form can name the offending field.

/**
 * One institutional resource survey. The id is generated by the browser, so a
 * retried submission lands on the same row. `institucion_clave` is the
 * normalized digest of the free-text institution name.
 */
export const riesgosFichas = pgTable(
  "riesgos_fichas",
  {
    id: uuid("id").primaryKey(),
    institucionClave: text("institucion_clave").notNull(),
    institucionNombre: text("institucion_nombre").notNull(),
    institucionTipo: riesgosInstitucionTipoEnum("institucion_tipo").notNull(),
    mesaGrupo: text("mesa_grupo").notNull(),
    isla: riesgosIslaEnum("isla").notNull(),
    principalNombre: text("principal_nombre").notNull(),
    principalCargo: text("principal_cargo").notNull(),
    principalCorreo: text("principal_correo").notNull(),
    principalTelefono: text("principal_telefono").notNull(),
    alternoNombre: text("alterno_nombre").notNull(),
    alternoCargo: text("alterno_cargo").notNull(),
    alternoCorreo: text("alterno_correo").notNull(),
    alternoTelefono: text("alterno_telefono").notNull(),
    brechas: text("brechas").notNull().default(""),
    observaciones: text("observaciones").notNull().default(""),
    estado: riesgosEstadoEnum("estado").notNull().default("pendiente"),
    notaRevision: text("nota_revision").notNull().default(""),
    revisadoPor: uuid("revisado_por").references(() => users.id, { onDelete: "set null" }),
    revisadoPorNombre: text("revisado_por_nombre"),
    revisadoAt: timestamp("revisado_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  },
  (t) => ({
    createdIdx: index("riesgos_fichas_created_idx").on(t.createdAt),
    institucionIdx: index("riesgos_fichas_institucion_idx").on(t.institucionClave),
  })
);

/** A resource always carries its ficha's review state. */
export const riesgosRecursos = pgTable(
  "riesgos_recursos",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    fichaId: uuid("ficha_id")
      .notNull()
      .references(() => riesgosFichas.id, { onDelete: "cascade" }),
    orden: integer("orden").notNull(),
    institucionClave: text("institucion_clave").notNull(),
    tipo: riesgosRecursoTipoEnum("tipo").notNull(),
    nombre: text("nombre").notNull(),
    claveActivo: text("clave_activo").notNull(),
    isla: riesgosIslaEnum("isla").notNull(),
    ubicacion: text("ubicacion").notNull(),
    unidad: text("unidad").notNull(),
    cantidadExistente: integer("cantidad_existente").notNull(),
    cantidadOperativa: integer("cantidad_operativa").notNull(),
    cantidadMovilizable: integer("cantidad_movilizable").notNull(),
    esTitular: boolean("es_titular").notNull(),
    disponibilidad: riesgosDisponibilidadEnum("disponibilidad").notNull(),
    restricciones: text("restricciones").notNull().default(""),
    detalles: jsonb("detalles").$type<Record<string, string>>().notNull().default({}),
    estado: riesgosEstadoEnum("estado").notNull().default("pendiente"),
  },
  (t) => ({
    fichaIdx: index("riesgos_recursos_ficha_idx").on(t.fichaId, t.orden),
    filtroIdx: index("riesgos_recursos_filtro_idx").on(t.estado, t.isla, t.tipo),
    // An owned asset is counted once per institution.
    validadoUnicoIdx: uniqueIndex("riesgos_recursos_validado_unico_idx")
      .on(t.institucionClave, t.tipo, t.claveActivo, t.isla)
      .where(sql`${t.estado} = 'validado' AND ${t.esTitular}`),
  })
);

