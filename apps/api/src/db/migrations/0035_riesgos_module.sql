-- One institutional resource survey. The institution is free text for now;
-- `institucion_clave` is its normalized digest, so "MAG" typed twice with
-- different spacing or case is still one institution. A managed catalog will
-- replace the free text later.
--
-- The id is generated by the browser when the form opens: a retry after a
-- dropped connection lands on the same row instead of creating a duplicate.
CREATE TABLE IF NOT EXISTS "riesgos_fichas" (
  "id" uuid PRIMARY KEY NOT NULL,
  "institucion_clave" text NOT NULL,
  "institucion_nombre" text NOT NULL,
  "institucion_tipo" "riesgos_institucion_tipo" NOT NULL,
  "mesa_grupo" text NOT NULL,
  "isla" "riesgos_isla" NOT NULL,
  "principal_nombre" text NOT NULL,
  "principal_cargo" text NOT NULL,
  "principal_correo" text NOT NULL,
  "principal_telefono" text NOT NULL,
  "alterno_nombre" text NOT NULL,
  "alterno_cargo" text NOT NULL,
  "alterno_correo" text NOT NULL,
  "alterno_telefono" text NOT NULL,
  "brechas" text DEFAULT '' NOT NULL,
  "observaciones" text DEFAULT '' NOT NULL,
  "estado" "riesgos_estado" DEFAULT 'pendiente' NOT NULL,
  "nota_revision" text DEFAULT '' NOT NULL,
  "revisado_por" uuid REFERENCES "users"("id") ON DELETE SET NULL,
  -- Kept apart from the FK so the trail survives the reviewer's deletion.
  "revisado_por_nombre" text,
  "revisado_at" timestamp with time zone,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT "riesgos_fichas_delegados_distintos" CHECK (lower("principal_correo") <> lower("alterno_correo"))
);
