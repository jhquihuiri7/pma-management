-- A resource always carries its ficha's state: reviewing a ficha rewrites the
-- state of every resource in it, in the same transaction.
CREATE TABLE IF NOT EXISTS "riesgos_recursos" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "ficha_id" uuid NOT NULL REFERENCES "riesgos_fichas"("id") ON DELETE CASCADE,
  "orden" integer NOT NULL,
  "institucion_clave" text NOT NULL,
  "tipo" "riesgos_recurso_tipo" NOT NULL,
  "nombre" text NOT NULL,
  -- Digest of tipo|nombre|isla|ubicación, normalized like institucion_clave.
  "clave_activo" text NOT NULL,
  "isla" "riesgos_isla" NOT NULL,
  "ubicacion" text NOT NULL,
  "unidad" text NOT NULL,
  "cantidad_existente" integer NOT NULL,
  "cantidad_operativa" integer NOT NULL,
  "cantidad_movilizable" integer NOT NULL,
  "es_titular" boolean NOT NULL,
  "disponibilidad" "riesgos_disponibilidad" NOT NULL,
  "restricciones" text DEFAULT '' NOT NULL,
  "detalles" jsonb DEFAULT '{}'::jsonb NOT NULL,
  "estado" "riesgos_estado" DEFAULT 'pendiente' NOT NULL,
  CONSTRAINT "riesgos_recursos_cantidades" CHECK (
    "cantidad_existente" >= 0
    AND "cantidad_operativa" BETWEEN 0 AND "cantidad_existente"
    AND "cantidad_movilizable" BETWEEN 0 AND "cantidad_operativa"
  ),
  -- Only the owner can commit a resource, and nothing unavailable moves.
  CONSTRAINT "riesgos_recursos_movilizable_titular" CHECK ("es_titular" OR "cantidad_movilizable" = 0),
  CONSTRAINT "riesgos_recursos_movilizable_disponible" CHECK ("disponibilidad" <> 'No disponible' OR "cantidad_movilizable" = 0)
);
